// ─── Helpers ───────────────────────────────────────────────────

export function getInvestorById(id: string): Investor | undefined {
  return INVESTORS.find((inv) => inv.id === id);
}

export function getInvestorsByIds(ids: string[]): Investor[] {
  return ids.map((id) => INVESTORS.find((inv) => inv.id === id)).filter(Boolean) as Investor[];
}

export function getIntroPathForInvestor(investorId: string): IntroPath | undefined {
  return INTRO_PATHS.find((p) => p.investorId === investorId);
}

export function getSyndicateRelationships(investorId: string): SyndicateRelationship[] {
  return SYNDICATE_RELATIONSHIPS.filter(
    (r) => r.sourceId === investorId || r.targetId === investorId
  );
}
